def kind_ru(kind: str) -> str:
    return KIND_RU.get(kind or "", kind or "")


def why_ru(rule_id: str, fallback: str = "") -> str:
    return TEXT_RU.get(rule_id, ("", ""))[0] or fallback


def patch_ru(rule_id: str, fallback: str = "") -> str:
    return TEXT_RU.get(rule_id, ("", ""))[1] or fallback


def fix_hint(rule_id: str) -> str:
    return FIX_HINT.get(rule_id, "")


def enrich_rule(rule: dict, family: dict | None = None) -> dict:
    """Копия правила с русскими полями — то, что отдаётся вкладке «Правила»."""
    item = dict(rule)
    item["kind_ru"] = kind_ru(rule.get("kind", ""))
    item["why_ru"] = why_ru(rule.get("id", ""), rule.get("why", ""))
    item["patch_ru"] = patch_ru(rule.get("id", ""), rule.get("patch", ""))
    item["fix_hint"] = fix_hint(rule.get("id", ""))
    if family:
        item["fix"] = family
    return item


